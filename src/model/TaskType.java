package model;

/**
 * Перечисление типов задач в системе управления задачами.
 *
 * <p>Определяет возможные типы задач, которые могут быть созданы и обработаны
 * в менеджере задач. Используется для идентификации типа задачи при сериализации,
 * десериализации и в логике обработки.</p>
 *
 * <p>Возможные типы:</p>
 * <ul>
 *   <li><b>TASK</b> - обычная задача, не имеющая подзадач и не принадлежащая эпику</li>
 *   <li><b>SUBTASK</b> - подзадача, которая принадлежит определенному эпику</li>
 *   <li><b>EPIC</b> - эпик, который объединяет несколько подзадач</li>
 * </ul>
 *
 * <p>Пример использования:</p>
 * <pre>
 * Task task = new Task(1, "Задача", "Описание", TaskStatus.NEW, TaskType.TASK);
 *
 * if (task.getType() == TaskType.EPIC) {
 *     System.out.println("Это эпик с подзадачами");
 * }
 * </pre>
 *
 * @see model.Task
 * @see model.Epic
 * @see model.Subtask
 * @see manager.FileBackedTaskManager#loadFromFile(java.io.File)
 */
public enum TaskType {
    /** Обычная самостоятельная задача */
    TASK,

    /** Подзадача, входящая в состав эпика */
    SUBTASK,

    /** Эпик, содержащий подзадачи */
    EPIC
}