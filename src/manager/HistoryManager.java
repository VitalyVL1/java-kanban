package manager;

import model.Task;

import java.util.List;

/**
 * Интерфейс, определяющий контракт менеджера для управления историей просмотров задач.
 *
 * <p>Отвечает за хранение и предоставление списка последних просмотренных пользователем задач.
 * История просмотров позволяет отслеживать, какие задачи были недавно запрошены,
 * и возвращать их в порядке от старых к новым.</p>
 *
 * <p>Основные возможности:</p>
 * <ul>
 *   <li><b>Добавление</b> - при просмотре задачи она добавляется в историю</li>
 *   <li><b>Удаление</b> - при удалении задачи она удаляется из истории</li>
 *   <li><b>Просмотр</b> - получение списка последних просмотренных задач</li>
 * </ul>
 *
 * <p>Особенности работы:</p>
 * <ul>
 *   <li>Повторный просмотр задачи перемещает её в конец истории (становится самой новой)</li>
 *   <li>История имеет ограниченный размер (обычно 10 задач)</li>
 *   <li>Старые задачи автоматически удаляются при превышении лимита</li>
 * </ul>
 *
 * @see model.Task
 * @see InMemoryHistoryManager
 * @see TaskManager#getHistory()
 */
public interface HistoryManager {

    /**
     * Возвращает список задач из истории просмотров.
     *
     * <p>Задачи возвращаются в порядке от самой старой к самой новой.
     * Первая задача в списке - наименее актуальная, последняя - самая свежая.</p>
     *
     * @return список последних просмотренных задач (может быть пустым)
     */
    List<Task> getHistory();

    /**
     * Добавляет задачу в историю просмотров.
     *
     * <p>Если задача уже присутствует в истории, она перемещается в конец (становится самой новой).
     * При превышении лимита размера истории самая старая задача удаляется.</p>
     *
     * @param task задача для добавления в историю (не может быть null)
     */
    void add(Task task);

    /**
     * Удаляет задачу из истории просмотров по идентификатору.
     *
     * <p>Используется для синхронизации истории с общим состоянием менеджера задач.
     * При удалении задачи из {@link TaskManager} она также должна удаляться из истории.</p>
     *
     * @param id идентификатор задачи, которую нужно удалить из истории
     */
    void remove(int id);
}