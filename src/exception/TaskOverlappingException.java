package exception;

/**
 * Исключение, выбрасываемое при пересечении временных интервалов задач.
 *
 * <p>Возникает при попытке создать или обновить задачу, временной интервал
 * которой пересекается с существующей задачей в списке приоритетов.</p>
 *
 * <p>Валидация временных пересечений важна для корректного планирования
 * и предотвращения конфликтов в расписании.</p>
 *
 * <p>Примеры ситуаций:</p>
 * <ul>
 *   <li>Создание задачи, время выполнения которой пересекается с другой задачей</li>
 *   <li>Обновление времени задачи, приводящее к пересечению с существующими</li>
 *   <li>Добавление подзадачи с временем, конфликтующим с другими задачами</li>
 * </ul>
 *
 * @see manager.InMemoryTaskManager
 * @see api.handler.TaskHttpHandler
 */
public class TaskOverlappingException extends RuntimeException {

    /**
     * Создает исключение с указанным сообщением.
     *
     * @param message детальное сообщение об ошибке
     */
    public TaskOverlappingException(String message) {
        super(message);
    }
}